import streamlit as st
import pandas as pd
import plotly.express as px
import numpy as np
import re
import os
from dotenv import load_dotenv
from zhipuai import ZhipuAI   

from src.utils.pdf_generator import generate_pdf
from src.utils.send_email import send_alert_email

load_dotenv()
API_KEY = os.getenv("new_api_key")


def valid_email(email: str) -> bool:
    pattern = r"^[\w\.-]+@[\w\.-]+\.\w+$"
    return re.match(pattern, email) is not None

def generate_llm_report(pred_df, disease):
    district_summaries = ""
    for _, row in pred_df.iterrows():
        district = row['district']
        cases = row['predicted_cases']
        risk = row['risk']
        if risk == "High":
            flag = " HIGH RISK"
            tone = f"{district} is currently facing a critical threat with an estimated {cases:.0f} cases. Immediate intervention is essential."
        elif risk == "Medium":
            flag = " Moderate Risk"
            tone = f"{district} shows a concerning trend with approximately {cases:.0f} predicted cases. Preventive measures should be reinforced."
        else:
            flag = " Low Risk"
            tone = f"{district} remains relatively stable with around {cases:.0f} cases expected. Continued vigilance is advised."
        district_summaries += f"- **{flag}** — {tone}\n"

    prompt = f"""
You are a public health advisor in Malawi. Based on the following district-level outbreak predictions for {disease}, write a professional advisory report for health professionals. Use British English. Include:

1. A brief introduction about the disease risk.
2. A bullet-point summary of each district with urgency flags.
3. General sanitation and prevention advice.
4. A call to action for health workers.
5. Do not include the date on which the report is generated.
6. at the end, say that it is generated by Malawi Outbreak Predictor App.
7. skip the line just after one district summary and before the next district summary.
8. remove the ##, use number for main points, do not use ** or other related symbols in the report.
9. Always use british simple and clear English.

District summaries:
{district_summaries}
"""

    try:
        client = ZhipuAI(api_key=API_KEY)  
        response = client.chat.completions.create(
            model="glm-4.5",
            messages=[{"role": "user", "content": prompt}],
            temperature=0.95,
            top_p=0.7
        )
        return response.choices[0].message.content
    except Exception as e:
        return f"❌ ZhipuAI error: {str(e)}"


def render_predictions(disease_df, climate_df, diseases, model_type, lstm_models, prophet_models):
    st.header("🔮 Predictions")
    disease = st.selectbox("Disease", diseases)
    recipient_email = st.text_input("Recipient Email Address (for Email Alerts)", placeholder="example@gmail.com")

    if "valid_email" not in st.session_state:
        st.session_state.valid_email = False

    with st.spinner("Generating predictions..."):
        pred_df = pd.DataFrame()
        for dist in disease_df['district'].unique():
            if model_type == "LSTM":
                model, scaler = lstm_models[disease]
                if model is None:
                    continue
                latest = pd.merge(
                    disease_df[(disease_df['district'] == dist) & (disease_df['disease'] == disease)].tail(4),
                    climate_df[climate_df['district'] == dist].tail(4),
                    on=['district', 'date']
                )
                if len(latest) < 4:
                    continue
                features = latest[['cases', 'rainfall_mm', 'temperature_c']].values
                features_scaled = scaler.transform(features)
                pred_cases = model.predict(features_scaled[np.newaxis, ...], verbose=0)[0, 0]
            else:
                models = prophet_models[disease]
                if dist not in models:
                    continue
                m = models[dist]
                future = m.make_future_dataframe(periods=4, freq='W')
                last_rain = climate_df[climate_df['district'] == dist]['rainfall_mm'].iloc[-1]
                last_temp = climate_df[climate_df['district'] == dist]['temperature_c'].iloc[-1]
                future['rainfall_mm'] = last_rain
                future['temperature_c'] = last_temp
                forecast = m.predict(future)
                pred_cases = forecast['yhat'].iloc[-1]

            pred_cases = max(0, pred_cases)
            risk = (
                "Low" if pred_cases < (300 if disease == 'Malaria' else 100 if disease == 'Cholera' else 25)
                else "Medium" if pred_cases < (600 if disease == 'Malaria' else 200 if disease == 'Cholera' else 50)
                else "High"
            )
            pred_df = pd.concat([pred_df, pd.DataFrame({
                'district': [dist],
                'predicted_cases': [pred_cases],
                'risk': [risk],
                'disease': [disease]
            })], ignore_index=True)

        st.dataframe(pred_df)
        fig = px.bar(pred_df, x='district', y='predicted_cases', color='risk',
                     title=f"{disease} Predictions (4 Weeks)")
        st.plotly_chart(fig, use_container_width=True)

      
        if st.button("Generate Advisory Report"):
            advisory_text = generate_llm_report(pred_df, disease)
            st.session_state.advisory_text = advisory_text
            st.text_area(" Advisory Preview", advisory_text, height=400)

      
        if st.button("Export PDF Report"):
            pdf_buffer = generate_pdf(pred_df)
            st.download_button("Download Report", pdf_buffer, "outbreak_report.pdf", "application/pdf")

       
        if st.button("Send Email Alerts"):
            if recipient_email == "" or not valid_email(recipient_email):
                st.session_state.valid_email = False
                st.error("Please enter a valid email address before sending.")
            else:
                st.session_state.valid_email = True
                advisory_text = st.session_state.get("advisory_text", generate_llm_report(pred_df, disease))
                send_alert_email(recipient_email, advisory_text, subject=f"{disease} Outbreak Prediction Alert")
                st.success("Email alert sent successfully!")
